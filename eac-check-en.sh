#!/usr/bin/env bash
# eac-check.sh - Checks the 8 system requirements of EAC Linux v2 aka EACv2 (Epic Games, announced 2026-10-14)
# Source: https://onlineservices.epicgames.com/news/introducing-easy-anti-cheat-linux-v2
# Unofficial script. Not affiliated with Epic Games.
# Read-only: it does't change anything on your system, again, read-only, doesn't touch anything
# Tested so far on my PC with Ubuntu budgie 24.04 and kubuntu 26.04. i write for my machine and maybe works on Ubuntu and derivatives. this will not burn ur PC, probably works on all debian derivates.
# Usage:  sudo bash eac-check.sh
#         (it also runs without sudo, but then it can't read the kernel signature)
# Run with Secure Boot ON: this is the EACv2 test on the first place, if u dont have Secure Boot EACv2 will fail yes or yes.
# anyways, these are approximate checks based on Epic's public blog post. Epic says the
# requirements may change, and the REAL verification is done by EAC itself 0_o

if [ -t 1 ]; then
  G=$'\e[32m'; R=$'\e[31m'; Y=$'\e[33m'; B=$'\e[1m'; D=$'\e[2m'; N=$'\e[0m'
else
  G=''; R=''; Y=''; B=''; D=''; N=''
fi
OK=0; BAD=0; WARN=0
FIX_CMDLINE=(); FIX_NOTES=()

ok()   { OK=$((OK+1));     printf '  %s✅%s %s\n' "$G" "$N" "$*"; }
bad()  { BAD=$((BAD+1));   printf '  %s❌%s %s\n' "$R" "$N" "$*"; }
warn() { WARN=$((WARN+1)); printf '  %s⚠️%s  %s\n' "$Y" "$N" "$*"; }
info() { printf '     %s%s%s\n' "$D" "$*" "$N"; }
hdr()  { printf '\n%s%s%s\n' "$B" "$*" "$N"; }

# "Well-known" keys according to Epic (distro Secure Boot CAs + Microsoft UEFI CA), whatever -_-
# Microslop UEFI CA is matched narrowly (a bare "Microslop" would also accept the Windows Production PCA)
WK_RE='Canonical Ltd\.? Master Certificate Authority|Canonical Ltd\.? Kernel Module Signing|Fedora Secure Boot CA|Universal Blue|Debian Secure Boot CA|openSUSE Secure Boot CA|SUSE Linux Enterprise Secure Boot CA|Rocky Linux Secure Boot Root CA|AlmaLinux Secure Boot CA|Microsoft Corporation UEFI CA|Microsoft UEFI CA'
# Kernel module signers
# if you see "Build time autogenerated kernel key", chill, that's normal,
# the distro makes it at build time to sign its own stuff, and the kernel holding it's signed too
MOD_RE='Build time autogenerated kernel key|Canonical|Fedora|Debian|openSUSE|SUSE|Rocky|AlmaLinux|Universal Blue|Microsoft Corporation UEFI CA|Microsoft UEFI CA'

# shellcheck disable=SC1091
. /etc/os-release 2>/dev/null
hdr "System"
info "${PRETTY_NAME:-Linux} · kernel $(uname -r) · $(uname -m)"
[ "$(id -u)" -ne 0 ] && info "Without sudo: cannot verify the kernel signature (check 1)."

# ---------- Secure Boot state (used by several checks) ----------
EFI=0; [ -d /sys/firmware/efi ] && EFI=1
SB=unknown; SBVAL=ok
if [ "$EFI" -eq 1 ]; then
  if command -v mokutil >/dev/null 2>&1; then
    o=$(mokutil --sb-state 2>&1)
    grep -qi 'SecureBoot enabled' <<<"$o" && SB=on
    grep -qi 'SecureBoot disabled' <<<"$o" && SB=off
    grep -qi 'validation is disabled' <<<"$o" && SBVAL=off
  fi
  if [ "$SB" = unknown ]; then
    f=$(ls /sys/firmware/efi/efivars/SecureBoot-* 2>/dev/null | head -n1)
    if [ -n "$f" ]; then
      if [ "$(od -An -t u1 -j4 -N1 "$f" 2>/dev/null | tr -d ' ')" = 1 ]; then SB=on; else SB=off; fi
    fi
  fi
else
  SB=off
fi

# ---------- 1. Signed kernel and modules ----------
hdr "1. Signed kernel and kernel modules (well-known keys, that mean corporate keys...)"
KIMG="/boot/vmlinuz-$(uname -r)"
if command -v sbverify >/dev/null 2>&1 && [ -r "$KIMG" ]; then
  sv=$(sbverify --list "$KIMG" 2>&1)
  if grep -qi 'No signature table' <<<"$sv"; then
    bad "The running kernel has no Secure Boot signature ($KIMG)"
  elif grep -Eiq "$WK_RE" <<<"$sv"; then
    ok "Kernel signed by a well-known CA: $(grep -Eio "$WK_RE" <<<"$sv" | head -n1)"
  else
    bad "Kernel is signed, but by a CA outside Epic's well-known list"
    info "$(grep -i 'issuer' <<<"$sv" | head -n1)"
  fi
else
  if [ ! -e "$KIMG" ]; then
    warn "$KIMG does not exist: if you boot a unified kernel image (UKI), the signed image lives on the ESP (EFI/Linux/*.efi) and this script don't check it."
  else
    warn "Could not read the kernel signature (sbsigntool missing, or run with sudo)."
    FIX_NOTES+=("To verify the kernel signature: sudo apt install sbsigntool, then run this script with sudo")
  fi
  [ "$SB" = on ] && info "Secure Boot is on and the kernel booted, so the firmware/shim accepted it (exact CA not confirmed)."
fi

unsigned=(); unknown=(); total=0
while read -r m; do
  [ -z "$m" ] && continue
  s=$(modinfo -F signer "$m" 2>/dev/null) || continue
  total=$((total+1))
  if [ -z "$s" ]; then
    unsigned+=("$m")
  elif ! grep -Eiq "$MOD_RE" <<<"$s"; then
    unknown+=("$m [$s]")
  fi
done < <(awk '{print $1}' /proc/modules 2>/dev/null)

if ! command -v modinfo >/dev/null 2>&1 || [ "$total" -eq 0 ]; then
  warn "Could not check module signatures (modinfo missing or /proc/modules empty)"
elif [ ${#unsigned[@]} -gt 0 ] || [ ${#unknown[@]} -gt 0 ]; then
  bad "Problematic loaded modules: ${#unsigned[@]} unsigned, ${#unknown[@]} with an unrecognized signer"
  for x in "${unsigned[@]}"; do info "unsigned: $x"; done
  for x in "${unknown[@]}"; do info "unrecognized signer: $x"; done
  FIX_NOTES+=("Out-of-tree modules (NVIDIA, VirtualBox, xone, etc.): use the distro's pre-signed packages; modules built by DKMS and signed with your own MOK will not pass")
else
  ok "All $total loaded modules have a recognized signature, yay!!"
fi

SE=$(cat /sys/module/module/parameters/sig_enforce 2>/dev/null)
if [ "$SE" = Y ]; then info "sig_enforce=Y (the kernel rejects unsigned modules)"; fi
if [ -n "$SE" ] && [ "$SE" != Y ]; then warn "sig_enforce=$SE: the kernel does not enforce module signatures"; fi

# MOK block only on UEFI systems (mokutil can mishandle on legacy BIOS, so.. older MOBOs are not allowed D: )
if [ "$EFI" -eq 1 ] && command -v mokutil >/dev/null 2>&1; then
  moks=$(mokutil --list-enrolled 2>&1)
  # Tell "couldn't read" apart from "read fine, and it's empty"
  if grep -qiE 'No such file or directory|MokListRT is empty' <<<"$moks"; then
    ok "No enrolled MOKs (MokListRT empty or missing)"
  elif [ -z "$moks" ] || grep -qiE 'failed|permission denied|cannot' <<<"$moks"; then
    warn "Could not read the enrolled MOKs (may need sudo, or a TTY for the password)"
    FIX_NOTES+=("Run this script with sudo to verify the enrolled MOKs")
  else
    nk=$(grep -c '^\[key' <<<"$moks")
    if [ "$nk" -eq 0 ]; then
      ok "No enrolled MOKs"
    else
      badk=$(awk '
        BEGIN { n=0 }
        /^\[key [0-9]+\]/ { if (n) print subj "|" iss; n++; subj=""; iss=""; next }
        /^[[:space:]]*Subject:/ { sub(/^[[:space:]]*Subject:[[:space:]]*/, ""); subj=$0 }
        /^[[:space:]]*Issuer:/  { sub(/^[[:space:]]*Issuer:[[:space:]]*/, ""); iss=$0 }
        END { if (n) print subj "|" iss }' <<<"$moks" | grep -Eiv "$WK_RE")
      if [ -z "$badk" ]; then
        ok "$nk enrolled MOK(s), all on the well-known list"
      else
        bad "Enrolled MOKs outside the well-known list (Epic requires all of them to be well-known):"
        while IFS= read -r l; do info "${l%%|*}"; done <<<"$badk"
        FIX_NOTES+=("Custom MOKs: Epic allows a separate boot entry for gaming without your own keys in MOK (your own keys belong in db, not in MOK)")
      fi
    fi
  fi
fi
info "Firmware db keys are not evaluated here, Epic only cares about the keys used in the boot session. ;P"

# ---------- 2. TPM 2.0 ----------
hdr "2. TPM 2.0"
tv=$(cat /sys/class/tpm/tpm0/tpm_version_major 2>/dev/null)
# Fallback for old kernels without tpm_version_major
if [ -z "$tv" ] && [ -r /sys/class/tpm/tpm0/device/caps ]; then
  grep -q '2\.0' /sys/class/tpm/tpm0/device/caps 2>/dev/null && tv=2
fi
if [ "$tv" = 2 ]; then
  ok "TPM 2.0 detected$([ -e /dev/tpmrm0 ] && echo ' (/dev/tpmrm0 present)')"
elif [ -e /sys/class/tpm/tpm0 ]; then
  bad "TPM present but version ${tv:-unknown} (2.0 required)"
else
  bad "No TPM visible, D:"
  FIX_NOTES+=("BIOS: enable the TPM (fTPM on AMD / PTT on Intel)")
fi

# ---------- 3. Secure Boot ----------
hdr "3. Secure Boot"
if [ "$EFI" -eq 0 ]; then
  bad "Booted in legacy BIOS mode, not UEFI. so sorry, but epic not allow too much older machines, and yes, thats sux"
  FIX_NOTES+=("BIOS: boot in UEFI mode")
elif [ "$SB" = on ] && [ "$SBVAL" = ok ]; then
  ok "Secure Boot enabled"
elif [ "$SB" = on ]; then
  bad "Secure Boot is on but shim validation is disabled (mokutil --disable-validation)"
  FIX_NOTES+=("Re-enable validation: sudo mokutil --enable-validation, then reboot")
elif [ "$SB" = off ]; then
  bad "Secure Boot disabled"
  FIX_NOTES+=("BIOS: enable Secure Boot")
else
  warn "Could not determine the Secure Boot state (install mokutil)"
fi

# ---------- 4. Measured boot ----------
# Epic only requires that measurements are present (GRUB and systemd-boot do it by default).
hdr "4. Measured boot (heuristic: PCR 4 and 7 contain data)"
P=/sys/class/tpm/tpm0/pcr-sha256
[ -d "$P" ] || P=/sys/class/tpm/tpm0/pcr-sha1   # TPM with only the SHA-1 bank active
if [ -d "$P" ]; then
  p4=$(tr -d ' \n' <"$P/4" 2>/dev/null)
  p7=$(tr -d ' \n' <"$P/7" 2>/dev/null)
  p8=$(tr -d ' \n' <"$P/8" 2>/dev/null)    # GRUB measures into PCR 8/9
  p9=$(tr -d ' \n' <"$P/9" 2>/dev/null)
  p11=$(tr -d ' \n' <"$P/11" 2>/dev/null)  # systemd-boot/UKI measures into PCR 11
  nz() { [ -n "$1" ] && ! [[ "$1" =~ ^0+$ ]]; }
  if nz "$p4" && nz "$p7"; then
    ok "Boot is being recorded in the TPM (PCR 4 and 7 contain data)"
    if nz "$p8" || nz "$p9" || nz "$p11"; then info "The bootloader also measures (PCR 8/9/11)."; fi
  elif [ -z "$p4" ] && [ -z "$p7" ]; then
    warn "Could not read the TPM PCRs (no TPM, or no readable PCR bank in sysfs)"
  else
    bad "PCR 4 or 7 is empty: boot is not being measured"
    FIX_NOTES+=("Use GRUB or systemd-boot with the TPM enabled; other boot managers may not measure")
  fi
  [ -s /sys/kernel/security/tpm0/binary_bios_measurements ] && info "TPM event log present."
else
  warn "Could't read the TPM PCRs (no TPM, or no readable PCR bank in sysfs)"
fi

# ---------- 5. IOMMU ----------
hdr "5. IOMMU enabled with passthrough disabled"
info "Epic exempts handheld devices (Steam Deck etc.), regular laptops/desktops require IOMMU, idk if that's right, im not 100% sure"
CPU=$(grep -m1 -oE 'GenuineIntel|AuthenticAMD' /proc/cpuinfo)
if [ ! -d /sys/kernel/iommu_groups ]; then
  bad "The kernel does not expose /sys/kernel/iommu_groups (IOMMU unsupported or disabled at compile time)"
  FIX_NOTES+=("Use a distro kernel with CONFIG_INTEL_IOMMU / CONFIG_AMD_IOMMU=y")
else
  ng=$(ls /sys/kernel/iommu_groups 2>/dev/null | wc -l)
  if [ "$ng" -eq 0 ]; then
    bad "IOMMU inactive (0 groups)"
    # iommu.passthrough=0 does not create groups; on AMD the IOMMU is only enabled from the BIOS
    FIX_NOTES+=("BIOS: enable Intel VT-d / AMD-Vi (IOMMU), then reboot")
    [ "$CPU" = GenuineIntel ] && FIX_CMDLINE+=("intel_iommu=on")
    [ "$CPU" = AuthenticAMD ] && FIX_CMDLINE+=("amd_iommu=on")
  elif grep -Eq '(^| )(iommu=pt|iommu\.passthrough=1)( |$)' /proc/cmdline; then
    bad "Passthrough enabled on the kernel command line (iommu=pt or iommu.passthrough=1)"
    FIX_NOTES+=("Remove iommu=pt / iommu.passthrough=1 from the kernel comand line")
    FIX_CMDLINE+=("iommu.passthrough=0")
  else
    types=$(cat /sys/kernel/iommu_groups/*/type 2>/dev/null)
    ident=$(grep -c '^identity' <<<"$types")
    dma=$(grep -c '^DMA' <<<"$types")
    if [ "$ident" -gt 0 ] && [ "$dma" -eq 0 ]; then
      bad "All IOMMU groups are in passthrough mode (identity)"
      FIX_CMDLINE+=("iommu.passthrough=0")
    elif [ "$ident" -gt 0 ]; then
      warn "$ident of $ng groups are identity-mapped (often a hardware quirk, e.g. a GPU); $dma use DMA translation"
    elif [ "$dma" -eq 0 ]; then
      warn "IOMMU active ($ng groups) but could not read the domain type"
    else
      ok "IOMMU active: $ng groups with DMA translation (no passthrough)"
    fi
  fi
fi

# ---------- 6. Lockdown ----------
hdr "6. Kernel lockdown in integrity mode"
lk=$(cat /sys/kernel/security/lockdown 2>/dev/null)
mode=$(grep -o '\[[a-z]*\]' <<<"$lk" | tr -d '[]')
case "$mode" in
  integrity)
    ok "Lockdown in integrity mode"
    if ! grep -qwF 'lockdown=integrity' /proc/cmdline; then
      warn "lockdown is not on the kernel command line; Epic asks for it to be 'explicitly enabled at boot time' (unknown whether EAC can tell) duhh!!!"
      info "To test without saving: in the GRUB menu press e and append lockdown=integrity to the linux line."
    fi
    ;;
  confidentiality)
    warn "Lockdown in confidentiality mode (stricter than integrity; Epic asks for integrity)"
    ;;
  none)
    bad "Lockdown disabled (none)"
    info "Expected with Secure Boot off. If you use unsigned modules (xone, DKMS), PLEASE!! don't make it permanent: test it with e in the GRUB menu."
    FIX_CMDLINE+=("lockdown=integrity")
    ;;
  *)
    bad "Lockdown LSM not found in this kernel"
    FIX_CMDLINE+=("lockdown=integrity")
    ;;
esac

# ---------- 7. kexec ----------
hdr "7. kexec disabled"
kx=$(sysctl -n kernel.kexec_load_disabled 2>/dev/null)
if [ "$kx" = 1 ]; then
  ok "kernel.kexec_load_disabled = 1"
elif [ -z "$kx" ]; then
  warn "Could not read kernel.kexec_load_disabled (kernel without kexec, or no sysctl)"
else
  bad "kexec enabled (kernel.kexec_load_disabled = ${kx:-?})"
  FIX_NOTES+=("Note: once you set kernel.kexec_load_disabled=1 via sysctl, it CANNOT be reverted to 0 in this boot session. Disable kexec: echo 'kernel.kexec_load_disabled=1' | sudo tee /etc/sysctl.d/99-eac.conf && sudo sysctl --system")
  FIX_NOTES+=("Alternative, closer to 'at boot time': disable in GRUB_CMDLINE_LINUX_DEFAULT, please be carefull if u edit grub, okay??")
  FIX_NOTES+=("This is irreversible within the current boot. To re-enable later, reboot (the sysctl.d file will re-apply it on every boot).")
fi

# ---------- 8. BPF LSM ----------
hdr "8. BPF Linux Security Module active"
lsm=$(cat /sys/kernel/security/lsm 2>/dev/null)
if [ -z "$lsm" ]; then
  warn "Could not read /sys/kernel/security/lsm (securityfs not mounted)"
elif grep -qw bpf <<<"$lsm"; then
  ok "BPF LSM active ($lsm)"
else
  cfg="/boot/config-$(uname -r)"
  if [ -r "$cfg" ] && ! grep -q '^CONFIG_BPF_LSM=y' "$cfg"; then
    bad "This kernel was built without BPF LSM (CONFIG_BPF_LSM)"
    FIX_NOTES+=("You need a distro kernel with CONFIG_BPF_LSM=y")
  else
    bad "BPF LSM is not active (current LSMs: ${lsm:-?})"
    # Rebuild lsm= without duplicating bpf and keeping the order
    newlsm=$(tr ',' '\n' <<<"$lsm" | grep -vx bpf | paste -sd, -)
    FIX_CMDLINE+=("lsm=${newlsm},bpf")
    FIX_NOTES+=("If your kernel command line already has lsm=..., replace it instead of adding a second one")
  fi
fi

# ---------- Summary ----------
hdr "Summary"
printf '  %s✅ %d%s   %s❌ %d%s   %s⚠️  %d%s\n' "$G" "$OK" "$N" "$R" "$BAD" "$N" "$Y" "$WARN" "$N"
if [ "$BAD" -eq 0 ] && [ "$WARN" -eq 0 ]; then
  printf '\n  %sNo failed requirements in these checks.%s\n' "$G" "$N"
elif [ "$BAD" -eq 0 ]; then
  printf '\n  %sNo failures, but %d check(s) with warnings.%s\n' "$Y" "$WARN" "$N"
  echo "  Warnings are checks that could not be performed, or whose evaluation by Epic is unclear: they do not count as passed."
  echo "  If information is missing, run with sudo and make sure mokutil and sbsigntool are installed."
else
  printf '\n  %s%d check(s) failed.%s\n' "$R" "$BAD" "$N"
  if [ ${#FIX_CMDLINE[@]} -gt 0 ]; then
    echo "  Suggested kernel parameters (GRUB_CMDLINE_LINUX_DEFAULT in /etc/default/grub):"
    echo "    $(printf '%s\n' "${FIX_CMDLINE[@]}" | awk '!s[$0]++' | tr '\n' ' ')"
    echo "  Then: sudo update-grub  "
  fi
  if [ ${#FIX_NOTES[@]} -gt 0 ]; then
    echo "  Other actions:"
    printf '%s\n' "${FIX_NOTES[@]}" | awk '!s[$0]++' | sed 's/^/    - /'
  fi
fi
if [ "$BAD" -gt 0 ] && [ "$WARN" -gt 0 ]; then
  info "Also $WARN warning(s): checks not performed or uncertain, not passed."
fi
echo
info "Approximate check by reading system state (read-only). The real verification is done by EAC when a protected game starts 0_0, and Epic says the requirements may change o_-. I don’t know how, but hopefully things like xone, xpadneo (for Xbox controllers), and the Nvidia drivers will work somehow ^_^"
